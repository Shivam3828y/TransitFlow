"""
TransitIQ — SQL Generator
Place this file at: pages/SQL_Generator.py

Expected optional session-state keys for an already-cleaned pandas DataFrame:
    cleaned_df, cleaned_data, processed_df, final_df, cleaned_dataset

If none is available, the page lets the user upload a cleaned CSV.
Dependencies: streamlit, pandas
"""

from __future__ import annotations

import datetime as dt
import decimal
import math
import re
from typing import Any

import pandas as pd
import streamlit as st


st.set_page_config(page_title="SQL Generator | TransitIQ", page_icon="🧾", layout="wide")

st.title("🧾 SQL Generator")
st.caption(
    "Detect the cleaned dataset schema, preview SQL INSERT statements, "
    "and download a .sql file. This page generates SQL only; it does not execute it."
)


# ---------- DataFrame discovery ----------

DATAFRAME_STATE_KEYS = (
    "cleaned_df",
    "cleaned_data",
    "processed_df",
    "final_df",
    "cleaned_dataset",
)


def get_cleaned_dataframe() -> tuple[pd.DataFrame | None, str | None]:
    """Return the first DataFrame found in known session-state keys."""
    for key in DATAFRAME_STATE_KEYS:
        value = st.session_state.get(key)
        if isinstance(value, pd.DataFrame) and not value.empty:
            return value.copy(), key
    return None, None


# ---------- SQL helpers ----------

DIALECTS = ("MySQL", "PostgreSQL", "SQLite")


def quote_identifier(identifier: str, dialect: str) -> str:
    """Quote a table or column identifier for the selected SQL dialect."""
    if dialect == "MySQL":
        return "`" + identifier.replace("`", "``") + "`"
    return '"' + identifier.replace('"', '""') + '"'


def safe_table_name(value: str) -> str:
    """Validate a simple schema-qualified table name (e.g. public.transport_logs)."""
    value = value.strip()
    if not value:
        raise ValueError("Enter a destination table name.")
    parts = value.split(".")
    if not all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", part) for part in parts):
        raise ValueError(
            "Use letters, numbers, underscores, and optional schema qualification "
            "(example: public.transport_logs). Do not include SQL punctuation."
        )
    return value


def sql_literal(value: Any, dialect: str) -> str:
    """Convert a scalar value into a SQL literal."""
    if value is None or pd.isna(value):
        return "NULL"

    if isinstance(value, (pd.Timestamp, dt.datetime, dt.date, dt.time)):
        return "'" + value.isoformat(sep=" " if isinstance(value, (pd.Timestamp, dt.datetime)) else "T").replace("'", "''") + "'"

    if isinstance(value, bool):
        if dialect == "PostgreSQL":
            return "TRUE" if value else "FALSE"
        return "1" if value else "0"

    if isinstance(value, (int,)):
        return str(value)

    if isinstance(value, (float,)):
        if math.isnan(value):
            return "NULL"
        if math.isinf(value):
            # Avoid generating non-portable infinity literals.
            return "NULL"
        return repr(value)

    if isinstance(value, decimal.Decimal):
        if not value.is_finite():
            return "NULL"
        return str(value)

    # Handle NumPy scalar types without requiring NumPy-specific branches.
    if hasattr(value, "item") and callable(value.item):
        try:
            return sql_literal(value.item(), dialect)
        except (ValueError, TypeError):
            pass

    # Escape apostrophes using SQL's standard string-literal escaping.
    text = str(value).replace("'", "''")
    return "'" + text + "'"


def infer_sql_type(series: pd.Series, dialect: str) -> str:
    """Infer a suggested SQL type from observed cleaned data."""
    dtype = series.dtype

    if pd.api.types.is_bool_dtype(dtype):
        return "BOOLEAN" if dialect == "PostgreSQL" else "INTEGER"
    if pd.api.types.is_integer_dtype(dtype):
        return "BIGINT"
    if pd.api.types.is_float_dtype(dtype):
        return "DOUBLE PRECISION" if dialect == "PostgreSQL" else "REAL"
    if pd.api.types.is_datetime64_any_dtype(dtype):
        return "TIMESTAMP"
    if pd.api.types.is_timedelta64_dtype(dtype):
        return "TEXT"
    # CSV does not preserve enough information to reliably infer constraints,
    # primary keys, foreign keys, or exact date/time semantics.
    return "TEXT"


def build_insert_sql(
    dataframe: pd.DataFrame,
    table_name: str,
    dialect: str,
    batch_size: int,
    selected_columns: list[str],
) -> str:
    """Build multi-row INSERT statements, split into batches."""
    quoted_table = ".".join(
        quote_identifier(part, dialect) for part in table_name.split(".")
    )
    quoted_columns = ", ".join(
        quote_identifier(column, dialect) for column in selected_columns
    )

    lines = [
        "-- Generated by TransitIQ SQL Generator",
        f"-- Dialect: {dialect}",
        f"-- Rows: {len(dataframe)}",
        "-- Review the target table schema before executing this file.",
        "",
    ]

    if dataframe.empty or not selected_columns:
        return "\n".join(lines + ["-- No rows or columns selected."])

    for start in range(0, len(dataframe), batch_size):
        chunk = dataframe.iloc[start : start + batch_size]
        lines.append(f"INSERT INTO {quoted_table} ({quoted_columns}) VALUES")
        value_rows = []

        for _, row in chunk.iterrows():
            values = ", ".join(sql_literal(row[column], dialect) for column in selected_columns)
            value_rows.append(f"    ({values})")

        lines.append(",\n".join(value_rows) + ";")
        lines.append("")

    return "\n".join(lines)


# ---------- UI: find or upload cleaned data ----------

dataframe, source_key = get_cleaned_dataframe()

if dataframe is not None:
    st.success(f"Using cleaned DataFrame from session state: `{source_key}`.")
    st.caption(
        "To connect this page to your pipeline, save the final cleaned pandas DataFrame "
        "under one of the supported session-state keys listed in the file header."
    )
    with st.expander("Use a different cleaned file instead"):
        uploaded_file = st.file_uploader(
            "Upload cleaned CSV",
            type=["csv"],
            key="sql_generator_override_upload",
        )
        if uploaded_file is not None:
            try:
                dataframe = pd.read_csv(uploaded_file)
                st.info("Using the uploaded CSV for this SQL export.")
            except Exception as exc:
                st.error(f"Could not read the CSV: {exc}")
                st.stop()
else:
    st.info(
        "No cleaned DataFrame was found in session state. Upload the cleaned CSV "
        "produced by the Data Cleaning page."
    )
    uploaded_file = st.file_uploader(
        "Upload cleaned CSV",
        type=["csv"],
        key="sql_generator_upload",
    )
    if uploaded_file is None:
        st.stop()
    try:
        dataframe = pd.read_csv(uploaded_file)
    except Exception as exc:
        st.error(f"Could not read the CSV: {exc}")
        st.stop()

if dataframe is None or dataframe.empty:
    st.warning("The selected dataset is empty. Upload a file containing at least one row.")
    st.stop()

# Duplicate column names make SQL generation ambiguous.
if dataframe.columns.duplicated().any():
    duplicated = dataframe.columns[dataframe.columns.duplicated()].astype(str).tolist()
    st.error(f"Duplicate column names were found: {duplicated}. Rename them before generating SQL.")
    st.stop()

st.subheader("1. Dataset overview")
m1, m2, m3 = st.columns(3)
m1.metric("Rows", f"{len(dataframe):,}")
m2.metric("Columns", f"{len(dataframe.columns):,}")
m3.metric("Missing cells", f"{int(dataframe.isna().sum().sum()):,}")

with st.expander("Preview cleaned data", expanded=True):
    st.dataframe(dataframe.head(20), use_container_width=True)

# ---------- Schema detection ----------

st.subheader("2. Detected schema")
schema_rows = []
for column in dataframe.columns:
    series = dataframe[column]
    non_null = series.dropna()
    schema_rows.append(
        {
            "Column": str(column),
            "Detected pandas type": str(series.dtype),
            "Suggested SQL type (MySQL)": infer_sql_type(series, "MySQL"),
            "Suggested SQL type (PostgreSQL)": infer_sql_type(series, "PostgreSQL"),
            "Suggested SQL type (SQLite)": infer_sql_type(series, "SQLite"),
            "Null values": int(series.isna().sum()),
            "Unique values": int(series.nunique(dropna=True)),
            "Sample value": str(non_null.iloc[0])[:80] if not non_null.empty else "(all NULL)",
        }
    )
st.dataframe(pd.DataFrame(schema_rows), use_container_width=True, hide_index=True)
st.caption(
    "Types are inferred from observed values. CSV data cannot reliably reveal primary keys, "
    "foreign keys, AUTO_INCREMENT/IDENTITY, or all database constraints."
)

# ---------- SQL generation controls ----------

st.subheader("3. Configure SQL export")
left, right = st.columns(2)
with left:
    dialect = st.selectbox("Target database dialect", DIALECTS, index=0)
    table_name_input = st.text_input(
        "Destination table name",
        value="transport_logs",
        help="Use a simple table name or schema.table, for example public.transport_logs.",
    )
with right:
    batch_size = st.number_input(
        "Rows per INSERT statement",
        min_value=1,
        max_value=5000,
        value=500,
        step=100,
        help="Batching keeps the generated SQL manageable for larger datasets.",
    )
    include_transaction = st.checkbox(
        "Wrap statements in a transaction",
        value=(dialect != "MySQL"),
        help="The target database and table engine must support transactions.",
    )

selected_columns = st.multiselect(
    "Columns to include",
    options=[str(c) for c in dataframe.columns],
    default=[str(c) for c in dataframe.columns],
    help="Clear a column if it is generated by the database or should not be inserted.",
)

# Keep the displayed names mapped to actual columns. Column labels are converted to str above.
column_lookup = {str(column): column for column in dataframe.columns}
actual_columns = [column_lookup[column] for column in selected_columns]

try:
    validated_table_name = safe_table_name(table_name_input)
except ValueError as exc:
    st.error(str(exc))
    st.stop()

if not actual_columns:
    st.warning("Select at least one column to generate INSERT statements.")
    st.stop()

if st.button("Generate SQL", type="primary", use_container_width=True):
    sql = build_insert_sql(
        dataframe=dataframe,
        table_name=validated_table_name,
        dialect=dialect,
        batch_size=int(batch_size),
        selected_columns=actual_columns,
    )

    if include_transaction and len(dataframe) > 0:
        if dialect == "MySQL":
            # START TRANSACTION is supported; actual rollback behavior depends on table engine.
            sql = "START TRANSACTION;\n\n" + sql + "\nCOMMIT;\n"
        else:
            sql = "BEGIN;\n\n" + sql + "\nCOMMIT;\n"

    st.session_state["transitiq_generated_sql"] = sql
    st.session_state["transitiq_generated_sql_filename"] = (
        re.sub(r"[^A-Za-z0-9_-]+", "_", validated_table_name.replace(".", "_")).strip("_")
        or "transitiq_export"
    ) + ".sql"

generated_sql = st.session_state.get("transitiq_generated_sql")

if generated_sql:
    st.subheader("4. SQL preview")
    st.caption("Preview is limited to the first 200 lines. The download contains the full SQL file.")
    preview_lines = generated_sql.splitlines()
    st.code("\n".join(preview_lines[:200]), language="sql")
    if len(preview_lines) > 200:
        st.caption(f"Showing 200 of {len(preview_lines):,} lines.")

    st.download_button(
        label="⬇️ Download .sql file",
        data=generated_sql.encode("utf-8"),
        file_name=st.session_state.get("transitiq_generated_sql_filename", "transitiq_export.sql"),
        mime="application/sql",
        use_container_width=True,
    )

    st.warning(
        "This tool generates SQL but does not execute it. Review the table name, column types, "
        "constraints, and data before running the file against a database."
    )
